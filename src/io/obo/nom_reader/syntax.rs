/// How a clause's value is written.
#[derive(Clone, Copy)]
enum Form {
    Boolean,
    Unquoted,
    Def,
    Synonym,
    SynonymAlt,
    Xref,
    PropertyValue,
    Id,
    Id2,
    /// `(RelationId ClassId) | ClassId`
    Id1or2,
    CreationDate,
    QuotedXrefs,
}

use Form::*;

/// The clauses all three kinds of frame share.
