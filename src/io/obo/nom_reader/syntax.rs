fn value(form: Form, s: &str) -> PResult<'_, Val<'_>> {
    let s = skip(s);
    match form {
        Boolean => boolean(s).map(|(r, v)| (r, Val::One(v))),
        Unquoted => unquoted(s).map(|(r, v)| (r, Val::One(v))),
        Def | SynonymAlt => definition(s),
        Synonym => synonym(s),
        Xref => xref(s),
        PropertyValue => property_value(s),
        Id => id(s).map(|(r, v)| (r, Val::One(v))),
        Id2 => {
            let (r, a) = id(s)?;
            let (r, b) = id(skip(r))?;
            Some((r, Val::Two(a, b)))
        }
        Id1or2 => {
            let (r, a) = id(s)?;
            match id(skip(r)) {
                Some((r, b)) => Some((r, Val::Two(a, b))),
                None => Some((r, Val::One(a))),
            }
        }
        CreationDate => creation_date(s).map(|(r, v)| (r, Val::One(v))),
        QuotedXrefs => {
            let (r, _) = quoted(s)?;
            let (r, _) = xref_list(skip(r))?;
            Some((r, Val::None))
        }
    }
}

/// A clause line: the clause, then `EOL`. The clause is the first known tag
/// whose value parses, else an unknown tag and what follows it.
fn clause_line(kind: FrameKind, s: &str) -> PResult<'_, Line<'_>> {
    let s = skip(s);
    // The tag runs to the first colon.
    let mut i = 0;
    loop {
        let t = &s[i..];
        if t.starts_with(':') {
            break;
        }
        if t.starts_with(is_ws) || newline(t).is_some() {
            return None;
        }
        i += obo_char(t)?;
    }
    if i == 0 {
        return None;
    }
    let tag_text = &s[..=i];
    let known = match kind {
        FrameKind::Term => term_tag(tag_text),
        FrameKind::Typedef => typedef_tag(tag_text),
        FrameKind::Instance => instance_tag(tag_text),
    };
    let after = &s[i + 1..];
    let (rest, tag, val) =
        match known.and_then(|(tag, form)| value(form, after).map(|(r, v)| (r, tag, v))) {
            Some(found) => found,
            None => {
                let t = skip(after);
                let rest = unquoted(t).map_or(after, |(r, _)| r);
                (rest, Tag::Unknown, Val::None)
            }
        };
    let (rest, quals) = eol(rest)?;
    Some((rest, Line { tag, val, quals }))
}

/// `(CommentSilent? ~ nl)*`.
fn blank_lines(mut s: &str) -> &str {
    loop {
        let t = comment(s).unwrap_or(s);
        match nl(t) {
            Some(r) => s = r,
            None => return s,
        }
    }
}

/// The first line of a frame, if the text starts one: the kind of frame.
fn frame_keyword(s: &str) -> Option<(FrameKind, &str)> {
    let s = skip(s);
    [
        ("[Term]", FrameKind::Term),
        ("[Typedef]", FrameKind::Typedef),
        ("[Instance]", FrameKind::Instance),
    ]
    .iter()
    .find_map(|(w, k)| s.strip_prefix(w).map(|r| (*k, r)))
}

/// The kind of frame `line` starts, if it does.
pub(super) fn frame_kind(line: &str) -> Option<FrameKind> {
    frame_keyword(line)
        .filter(|(_, rest)| nl(rest).is_some())
        .map(|(k, _)| k)
}

/// Does `line` start a frame?
pub(super) fn starts_frame(line: &str) -> bool {
    frame_keyword(line).is_some_and(|(_, rest)| nl(rest).is_some())
}

/// One `EntityFrame`, with the blank and comment lines before it. `None`
/// if the text does not start one.
pub(super) fn frame(s: &str) -> PResult<'_, Frame<'_>> {
    let s = blank_lines(s);
    let (kind, rest) = frame_keyword(s)?;
    let rest = blank_lines(nl(rest)?);
    let rest = skip(rest).strip_prefix("id:")?;
    let (rest, id_text) = id(skip(rest))?;
    let (mut rest, _) = eol(rest)?;
    let mut lines = Vec::new();
    loop {
        if let Some((r, line)) = clause_line(kind, rest) {
            lines.push(line);
            rest = r;
            continue;
        }
        let t = comment(rest).unwrap_or(rest);
        match nl(t) {
            Some(r) => rest = r,
            None => break,
        }
    }
    Some((
        rest,
        Frame {
            kind,
            id: id_text,
            lines,
        },
    ))
}
